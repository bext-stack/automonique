/// Maximum bytes of provider payload carried inline in a raw record.
pub const MAX_INLINE_RAW_BYTES: usize = 64 * 1024;

/// Maximum UTF-8 byte length of a source event type or cursor.
pub const MAX_SOURCE_FIELD_BYTES: usize = 256;

/// How much a record may be relied upon.
///
/// Required on every recorded event; there is no default and no inferred value.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum Authority {
    /// A completed provider message or reconciled history.
    Authoritative,
    /// Generated by Automonique rather than observed from a provider.
    Synthetic,
}

impl Authority {
    /// Stable lowercase wire spelling.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Authoritative => "authoritative",
            Self::Synthetic => "synthetic",
        }
    }
}

