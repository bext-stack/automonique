/// Decisions recorded against provider approval requests.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct ApprovalLedger {
    receipts: Vec<ApprovalReceipt>,
}

impl ApprovalLedger {
    /// Start an empty ledger.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            receipts: Vec::new(),
        }
    }

    /// Record a decision, idempotently.
    ///
    /// Replaying the same decision for the same request returns the identical
    /// receipt, including its original timestamp.
    ///
    /// # Errors
    ///
    /// Returns [`EventError::ApprovalConflict`] when a differing decision is
    /// offered for a request already decided. A decision is never replaced.
    pub fn decide(
        &mut self,
        request: &ProviderApprovalRequest,
        decision: ApprovalDecision,
        at: EpochMillis,
    ) -> Result<ApprovalReceipt, EventError> {
        if let Some(existing) = self
            .receipts
            .iter()
            .find(|receipt| receipt.request == *request.request())
        {
            return if existing.decision == decision {
                Ok(existing.clone())
            } else {
                Err(EventError::ApprovalConflict {
                    recorded: existing.decision,
                    offered: decision,
                })
            };
        }
        let receipt = ApprovalReceipt {
            request: request.request().clone(),
            decision,
            at,
        };
        self.receipts.push(receipt.clone());
        Ok(receipt)
    }
}

/// How long each class of record is kept.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RetentionPolicy {
    preview_ms: i64,
    authoritative_ms: i64,
}

impl RetentionPolicy {
    /// Declare separate horizons for previews and authoritative records.
    ///
    /// # Errors
    ///
    /// Returns [`EventError::RetentionWouldOutliveEvidence`] when previews
    /// would be kept at least as long as the evidence derived from them, which
    /// inverts the point of the split.
    pub const fn new(preview_ms: i64, authoritative_ms: i64) -> Result<Self, EventError> {
        if preview_ms >= authoritative_ms {
            return Err(EventError::RetentionWouldOutliveEvidence {
                preview_ms,
                authoritative_ms,
            });
        }
        Ok(Self {
            preview_ms,
            authoritative_ms,
        })
    }

    /// Preview horizon in milliseconds.
    #[must_use]
    pub const fn preview_ms(self) -> i64 {
        self.preview_ms
    }

    /// Authoritative horizon in milliseconds.
    #[must_use]
    pub const fn authoritative_ms(self) -> i64 {
        self.authoritative_ms
    }

    /// Drop previews older than the preview horizon.
    ///
    /// Takes previews only. There is no signature through which expiring a
    /// preview could reach a [`RecordedEvent`], so preview expiry cannot remove
    /// the record a report was derived from.
    pub fn expire_previews(self, previews: &mut Vec<PreviewEvent>, now: EpochMillis) {
        previews.retain(|preview| {
            now.as_millis().saturating_sub(preview.at().as_millis()) < self.preview_ms
        });
    }
}

fn source_field(value: &str, field: &'static str) -> Result<(), EventError> {
    if value.is_empty()
        || value.len() > MAX_SOURCE_FIELD_BYTES
        || value.chars().any(char::is_control)
    {
        return Err(EventError::SourceFieldInvalid { field });
    }
    Ok(())
}
