//! Normalized provider events, authority and cursor semantics.
//!
//! The central rule is that what was *shown* can never become what was
//! *decided*. Preview deltas and recorded events are separate types rather than
//! one type with an authority field a caller must remember to check, so terminal
//! reporting cannot accept a preview:
//!
//! First, the same construction that does compile, so the failure below cannot
//! be blamed on anything but the type it is meant to reject:
//!
//! ```
//! use automonique_protocol::event::{EventCoordinates, PreviewEvent};
//! use automonique_protocol::primitives::EpochMillis;
//! use automonique_protocol::provider::ProviderSessionId;
//!
//! let coordinates = EventCoordinates::new(
//!     ProviderSessionId::new("s-1").unwrap(), None, None,
//! );
//! let preview = PreviewEvent::new(1, coordinates, EpochMillis::from_millis(0), "partial");
//! assert_eq!(preview.text(), "partial");
//! ```
//!
//! Now the identical preview, offered to terminal reporting:
//!
//! ```compile_fail
//! use automonique_protocol::event::{EventCoordinates, PreviewEvent, RunTimeline};
//! use automonique_protocol::primitives::EpochMillis;
//! use automonique_protocol::provider::ProviderSessionId;
//!
//! let coordinates = EventCoordinates::new(
//!     ProviderSessionId::new("s-1").unwrap(), None, None,
//! );
//! let preview = PreviewEvent::new(1, coordinates, EpochMillis::from_millis(0), "partial");
//! let mut timeline = RunTimeline::new();
//! // Terminal reporting accepts recorded events only.
//! timeline.record(preview);
//! ```
//!
//! Nothing here connects to a provider, parses a vendor payload into its
//! vendor-specific shape, writes a journal or resolves an artifact.

