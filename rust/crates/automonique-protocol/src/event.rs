/// Why an event, cursor or approval was refused.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EventError {
    /// A raw payload exceeded the inline ceiling and needs an artifact.
    RawPayloadTooLarge {
        /// Maximum inline bytes.
        max_bytes: usize,
        /// Supplied bytes.
        actual_bytes: usize,
    },
    /// A bounded source field was empty, oversized or contained a control.
    SourceFieldInvalid {
        /// The rejected field.
        field: &'static str,
    },
    /// A sequence did not strictly increase.
    SequenceNotIncreasing {
        /// Last accepted sequence.
        last: u64,
        /// Offered sequence.
        offered: u64,
    },
    /// A second terminal record was offered for one run.
    TerminalAlreadyRecorded {
        /// Sequence of the terminal already held.
        existing: u64,
    },
    /// An event arrived after the run reached its terminal state.
    RunAlreadyTerminal,
    /// A cursor was moved backwards.
    CursorWentBackwards {
        /// Current cursor position.
        current: u64,
        /// Offered position.
        offered: u64,
    },
    /// A second, differing decision was offered for one approval.
    ApprovalConflict {
        /// The decision already recorded.
        recorded: ApprovalDecision,
        /// The decision offered.
        offered: ApprovalDecision,
    },
    /// Preview retention would outlive authoritative retention.
    RetentionWouldOutliveEvidence {
        /// Preview horizon in milliseconds.
        preview_ms: i64,
        /// Authoritative horizon in milliseconds.
        authoritative_ms: i64,
    },
}

impl EventError {
    /// Stable machine-readable category.
    #[must_use]
    pub const fn category(&self) -> &'static str {
        match self {
            Self::RawPayloadTooLarge { .. } => "raw_payload_too_large",
            Self::SourceFieldInvalid { .. } => "source_field_invalid",
            Self::SequenceNotIncreasing { .. } => "sequence_not_increasing",
            Self::TerminalAlreadyRecorded { .. } => "terminal_already_recorded",
            Self::RunAlreadyTerminal => "run_already_terminal",
            Self::CursorWentBackwards { .. } => "cursor_went_backwards",
            Self::ApprovalConflict { .. } => "approval_conflict",
            Self::RetentionWouldOutliveEvidence { .. } => "retention_would_outlive_evidence",
        }
    }
}

impl fmt::Display for EventError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::RawPayloadTooLarge {
                max_bytes,
                actual_bytes,
            } => write!(
                formatter,
                "raw payload is {actual_bytes} bytes; the inline maximum is {max_bytes}"
            ),
            Self::SourceFieldInvalid { field } => {
                write!(formatter, "source field {field} is invalid")
            }
            Self::SequenceNotIncreasing { last, offered } => write!(
                formatter,
                "sequence {offered} does not increase past {last}"
            ),
            Self::TerminalAlreadyRecorded { existing } => write!(
                formatter,
                "the run already reached its terminal record at sequence {existing}"
            ),
            Self::RunAlreadyTerminal => formatter.write_str("the run is already terminal"),
            Self::CursorWentBackwards { current, offered } => write!(
                formatter,
                "cursor cannot move from {current} back to {offered}"
            ),
            Self::ApprovalConflict { recorded, offered } => write!(
                formatter,
                "approval already decided {} and cannot become {}",
                recorded.as_str(),
                offered.as_str()
            ),
            Self::RetentionWouldOutliveEvidence {
                preview_ms,
                authoritative_ms,
            } => write!(
                formatter,
                "preview retention of {preview_ms}ms would outlive authoritative \
                 retention of {authoritative_ms}ms"
            ),
        }
    }
}

impl Error for EventError {}

/// A bounded raw provider record, or a reference to one held as an artifact.
///
/// An unbounded raw record is not representable, so provider output cannot fill
/// durable storage through this type.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum RawPayload {
    /// Payload small enough to carry inline.
    Inline(Vec<u8>),
    /// Payload held as an artifact, referenced by digest.
    Artifact(String),
}

/// One bounded raw provider record.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RawProviderRecord {
    provenance: BinaryProvenance,
    source_type: String,
    source_cursor: String,
    payload: RawPayload,
}

impl RawProviderRecord {
    /// Record a provider event with an inline payload.
    ///
    /// # Errors
    ///
    /// Returns [`EventError::RawPayloadTooLarge`] above the inline ceiling — a
    /// caller must reference an artifact instead — or
    /// [`EventError::SourceFieldInvalid`] for a bad coordinate.
    pub fn inline(
        provenance: BinaryProvenance,
        source_type: &str,
        source_cursor: &str,
        payload: Vec<u8>,
    ) -> Result<Self, EventError> {
        source_field(source_type, "source_type")?;
        source_field(source_cursor, "source_cursor")?;
        if payload.len() > MAX_INLINE_RAW_BYTES {
            return Err(EventError::RawPayloadTooLarge {
                max_bytes: MAX_INLINE_RAW_BYTES,
                actual_bytes: payload.len(),
            });
        }
        Ok(Self {
            provenance,
            source_type: source_type.to_owned(),
            source_cursor: source_cursor.to_owned(),
            payload: RawPayload::Inline(payload),
        })
    }

    /// Record a provider event whose payload lives in an artifact.
    ///
    /// # Errors
    ///
    /// Returns [`EventError::SourceFieldInvalid`] for a bad coordinate.
    pub fn artifact(
        provenance: BinaryProvenance,
        source_type: &str,
        source_cursor: &str,
        digest: &str,
    ) -> Result<Self, EventError> {
        source_field(source_type, "source_type")?;
        source_field(source_cursor, "source_cursor")?;
        source_field(digest, "artifact_digest")?;
        Ok(Self {
            provenance,
            source_type: source_type.to_owned(),
            source_cursor: source_cursor.to_owned(),
            payload: RawPayload::Artifact(digest.to_owned()),
        })
    }

    /// The binary this record came from.
    #[must_use]
    pub const fn provenance(&self) -> &BinaryProvenance {
        &self.provenance
    }

    /// The provider's own event type.
    #[must_use]
    pub fn source_type(&self) -> &str {
        &self.source_type
    }

    /// The provider's own sequence or cursor.
    #[must_use]
    pub fn source_cursor(&self) -> &str {
        &self.source_cursor
    }

    /// The bounded payload.
    #[must_use]
    pub const fn payload(&self) -> &RawPayload {
        &self.payload
    }
}

